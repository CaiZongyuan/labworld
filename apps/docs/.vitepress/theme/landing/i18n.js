export const DICT = { en: {}, zh: {} };
for (const k in T) {
  DICT.en[k] = T[k][0];
  DICT.zh[k] = T[k][1] ?? T[k][0];
}

export function translate(lang, key, vars) {
  let text = DICT[lang]?.[key] ?? DICT.en[key] ?? key;
  if (vars)
    for (const name in vars)
      text = text.split(`{${name}}`).join(String(vars[name]));
  return text;
}

